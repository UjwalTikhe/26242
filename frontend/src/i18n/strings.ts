const dict: Record<Lang, typeof en> = { en, hi, mr: hi };

export function translate(key: keyof typeof en, lang: Lang, vars?: Record<string, string | number>): string {
  const tmpl = dict[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return tmpl;
  return tmpl.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export type TKey = keyof typeof en;

